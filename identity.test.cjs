const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
const lines = html.split('\n');
const prefixes = ['const nu=', 'const norm=', 'const jobUrlKey=', 'const keysOf=', 'const sim=', 'const unionS=', 'function mergeInto', 'const strongMatch=', 'function dedupe'];
const code = prefixes.map(p => { const line=lines.find(s=>s.startsWith(p)); if(!line)throw Error('Missing '+p); return line; }).join('\n');
const ctx={URL};vm.createContext(ctx);vm.runInContext(code+'\nthis.dedupe=dedupe;',ctx);
const j=(co,role,url,id=null,city='Paris')=>({companyName:co,roleTitle:role,city,canonicalUrl:url,providerJobId:id,sources:[{label:co,url,applyUrl:url}],flags:[],dataQualityScore:30});
const a=j('Alpha','Analyst','https://jobs.example/search?id=1');
const b=j('Beta','Analyst','https://jobs.example/search?id=2');
assert.equal(ctx.dedupe([a,b]).out.length,2);
assert.equal(ctx.dedupe([j('A','Analyst','https://jobs.example/search#1'),j('B','Analyst','https://jobs.example/search#2')]).out.length,2);
assert.equal(ctx.dedupe([j('A','Analyst','https://jobs.example/jobs'),j('B','Analyst','https://jobs.example/jobs')]).out.length,2);
assert.equal(ctx.dedupe([j('A','Analyst','https://jobs.example/123','id'),j('A','Analyst','https://jobs.example/123','id')]).out.length,1);
assert.equal(ctx.dedupe([j('A','Analyst','https://jobs.example/1'),j('A','Associate','https://jobs.example/2')]).out.length,2);
assert.equal(ctx.dedupe([j('A','Analyst','https://jobs.example/1',null,'Paris'),j('A','Analyst','https://jobs.example/2',null,'London')]).out.length,2);
console.log('Identity regression tests passed');
